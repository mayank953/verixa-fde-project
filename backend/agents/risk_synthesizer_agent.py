def _safe_dict(val: Any, label: str = "") -> Dict:
    if isinstance(val, dict):
        return val
    if val is None:
        return {}
    logger.warning(f"[RiskSynthesizer] Expected dict for '{label}', got {type(val).__name__} — using {{}}")
    return {}


class RiskSynthesizerAgent:
    """Final aggregation agent that produces the fraud risk score and report."""

    SYSTEM_PROMPT = """You are a senior fraud risk officer.
Given outputs from web scraping, SQL analysis, and knowledge graph traversal,
produce a final risk assessment. Be precise and actionable.
Risk scale: 0.00-0.30=LOW  0.31-0.60=MEDIUM  0.61-0.80=HIGH  0.81-1.00=CRITICAL
Recommendations must be specific and proportional to the risk level."""

    WEIGHTS = {
        "web":   0.25,
        "sql":   0.40,
        "graph": 0.35
    }

    def __init__(self, llm):
        self.llm = llm

    def _compute_risk_score(
        self,
        web_intel: Dict,
        sql_findings: Dict,
        graph_insights: Dict,
        customer_info: Dict = None,
    ) -> float:
        web_score   = float(web_intel.get("web_risk_score", 0))
        sql_score   = float(sql_findings.get("sql_risk_score", 0))
        graph_score = float(graph_insights.get("graph_risk_score", 0))

        # PRIMARY: read directly from customer_info — psycopg2 gives clean Python types
        # no string parsing needed, always reliable on both local and Cloud SQL
        customer_info = customer_info or {}
        db_score   = float(customer_info.get("risk_score", 0) or 0)
        is_flagged = bool(customer_info.get("is_flagged", False))

        # FALLBACK: try SQL query_results if customer_info not available
        if db_score == 0.0:
            query_results = sql_findings.get("query_results", {})
            if not isinstance(query_results, dict):
                query_results = {}
            db_profile = query_results.get("customer_risk_profile", [])
            if not isinstance(db_profile, list):
                db_profile = []

            def _row_val(row, key, idx, default):
                if isinstance(row, dict):
                    return row.get(key, default)
                if isinstance(row, (list, tuple)):
                    try:
                        return row[idx]
                    except:
                        return default
                return default

            db_score   = float(_row_val(db_profile[0], "db_risk_score", 3, 0)) if db_profile else 0.0
            is_flagged = bool(_row_val(db_profile[0], "is_flagged", 4, False)) if db_profile else False

        # Weighted composite from agent signals
        agent_composite = (
            web_score   * self.WEIGHTS["web"] +
            sql_score   * self.WEIGHTS["sql"] +
            graph_score * self.WEIGHTS["graph"]
        )

        # DB score is hard floor — never go below it
        composite = max(agent_composite, db_score)
        if is_flagged:
            composite = max(composite, 0.61)    # minimum HIGH if manually flagged
        if db_score >= 0.81:
            composite = max(composite, db_score)  # CRITICAL stays CRITICAL

        logger.info(
            f"[RiskSynthesizer] score calc: web={web_score:.2f} sql={sql_score:.2f} "
            f"graph={graph_score:.2f} db={db_score:.2f} flagged={is_flagged} "
            f"agent_composite={agent_composite:.2f} final={min(composite,1.0):.4f}"
        )

        return round(min(composite, 1.0), 4)

    def _score_to_level(self, score: float) -> str:
        if score <= 0.30:   return "LOW"
        elif score <= 0.60: return "MEDIUM"
        elif score <= 0.80: return "HIGH"
        else:               return "CRITICAL"

    def _score_to_action(self, score: float, level: str) -> str:
        actions = {
            "LOW":      "No immediate action required. Monitor for 30 days.",
            "MEDIUM":   "Flag for enhanced due diligence. Request additional KYC documents.",
            "HIGH":     "Suspend account pending manual review. Alert compliance team.",
            "CRITICAL": "Immediately freeze account. File SAR. Escalate to fraud ops."
        }
        return actions.get(level, "Review required.")

    def _collect_fraud_indicators(
        self, web_intel: Dict, sql_findings: Dict, graph_insights: Dict
    ) -> List[Dict]:
        indicators = []

        web_type_labels = {
            "adverse_google_results": "Adverse Online Presence",
            "adverse_news":           "Adverse News Coverage",
            "data_breach_exposure":   "Data Breach Exposure",
            "disposable_email":       "Suspicious Email Address",
        }
        for signal in web_intel.get("signals", []):
            if isinstance(signal, dict):
                sig_type   = signal.get("type", "")
                sig_detail = signal.get("detail", "")
                label      = web_type_labels.get(sig_type, sig_type.replace("_", " ").title())
                indicators.append({
                    "source":      "WEB",
                    "flag":        sig_type.upper(),
                    "description": f"**{label}** — {sig_detail}"
                })
            elif isinstance(signal, str):
                indicators.append({"source": "WEB", "flag": "WEB_SIGNAL", "description": signal})

        anomaly_details = sql_findings.get("anomaly_details", [])
        if anomaly_details:
            for d in anomaly_details:
                indicators.append({
                    "source":      "SQL",
                    "flag":        d.get("flag", "SQL_ANOMALY"),
                    "description": d.get("description", d.get("flag", ""))
                })
        else:
            for flag in sql_findings.get("anomaly_flags", []):
                indicators.append({"source": "SQL", "flag": flag, "description": flag.replace("_", " ").title()})

        graph_pattern_labels = {
            "SHELL_COMPANY_NETWORK":     "Shell Company Network detected — multiple layered entities with no legitimate business purpose",
            "CIRCULAR_TRANSACTIONS":     "Circular transaction flow — funds routed back to origin through intermediaries",
            "RAPID_FUND_MOVEMENT":       "Rapid layering — funds moved across multiple accounts within short timeframe",
            "OFFSHORE_CONNECTIONS":      "Offshore account linkages — connections to high-risk jurisdictions",
            "SHARED_DEVICE_MULTIPLE_ID": "Device shared across multiple customer identities — strong identity fraud signal",
        }
        for pattern in graph_insights.get("fraud_patterns", []):
            indicators.append({
                "source":      "GRAPH",
                "flag":        pattern,
                "description": graph_pattern_labels.get(
                    pattern,
                    f"Network pattern: {pattern.replace('_', ' ').title()}"
                )
            })

        return indicators

    def _build_report(
        self, entity_id: str, entity_type: str,
        risk_score: float, risk_level: str,
        fraud_indicators: List[Dict], fraud_summary: str, recommendations: List[str],
        web_intel: Dict, sql_findings: Dict, graph_insights: Dict
    ) -> str:

        def bullet_list(items) -> str:
            if not items:
                return "- No significant findings\n"
            result = []
            for item in items:
                if isinstance(item, str):
                    result.append(f"- {item}")
                else:
                    result.append(f"- {item}")
            return "\n".join(result)

        def render_indicators(indicators: List[Dict]) -> str:
            if not indicators:
                return "- No fraud indicators detected\n"
            lines = []
            source_order = ["WEB", "SQL", "GRAPH"]
            source_emoji = {"WEB": "🌐", "SQL": "🗄️", "GRAPH": "🕸️"}
            grouped: Dict[str, List] = {"WEB": [], "SQL": [], "GRAPH": []}
            for ind in indicators:
                src = ind.get("source", "SQL")
                grouped.setdefault(src, []).append(ind)
            for src in source_order:
                if not grouped.get(src):
                    continue
                lines.append(f"\n**{source_emoji.get(src,'')} {src} Signals:**")
                for ind in grouped[src]:
                    lines.append(f"- {ind.get('description', ind.get('flag', ''))}")
            return "\n".join(lines)

        if fraud_summary:
            fraud_summary_section = fraud_summary
        else:
            fraud_summary_section = (
                "_No significant fraud indicators detected. "
                "Entity appears low-risk based on available data._"
            )

        news     = _safe_dict(web_intel.get("news",       {}), "news")
        breach   = _safe_dict(web_intel.get("breach",     {}), "breach")
        email_fr = _safe_dict(web_intel.get("email_fraud",{}), "email_fraud")

        web_items = [f"Signal count: {web_intel.get('signal_count', 0)}"]
        if not breach.get("skipped"):
            bc = breach.get("breach_count", 0)
            if bc > 0:
                bn = ", ".join(breach.get("breach_names", [])[:3])
                web_items.append(f"Data breaches: found in {bc} database(s) — {bn}")
            else:
                web_items.append("Data breaches: none found")
        if email_fr.get("risk_signal"):
            web_items.append(
                f"Email risk: fraud score {email_fr.get('fraud_score', 'N/A')} | "
                f"disposable={email_fr.get('disposable', False)}"
            )

        news_narrative = web_intel.get("news_narrative", "")
        if not news_narrative:
            neg = [m for m in news.get("mentions", []) if m.get("sentiment") == "negative"]
            news_narrative = " | ".join(
                f"{m.get('source','')}: {m.get('headline','')}" for m in neg[:3]
            ) if neg else ""

        if news_narrative and news_narrative != "No adverse news found.":
            web_items.insert(0, f"Adverse Google results: {news.get('negative_mentions', 0)} negative — see News Intelligence below")

        web_section = bullet_list(web_items)

        sql_items = []
        sql_sum = sql_findings.get("summary", "")
        if sql_sum:
            sql_items.append(f"**Analysis:** {sql_sum}")
        tc  = sql_findings.get("transaction_count", 0)
        amt = sql_findings.get("total_amount", 0)
        if tc:
            sql_items.append(f"Lifetime transactions: {int(tc)} | Total amount: ${float(amt or 0):,.0f}")
        cc  = sql_findings.get("country_count", 0)
        ctr = sql_findings.get("countries", "")
        if cc:
            sql_items.append(f"Geographic spread: {cc} countries ({ctr})")
        kf = sql_findings.get("key_findings", [])
        if kf:
            sql_items.append(f"Key findings: {', '.join(kf)}")
        if not sql_items:
            sql_items = ["No significant transaction anomalies detected"]
        sql_section = bullet_list(sql_items)

        graph_section = bullet_list([
            f"Suspicious clusters: {graph_insights.get('suspicious_clusters', 0)}",
            f"Fraud patterns: {', '.join(graph_insights.get('fraud_patterns', [])) or 'None'}",
            f"Connected entities: {len(graph_insights.get('connected_entities', []))}"
        ])

        news_section = ""
        if news_narrative and news_narrative != "No adverse news found.":
            news_section = f"\n### 📰 News Intelligence\n{news_narrative}\n"
            neg_articles = [m for m in news.get("mentions", []) if m.get("sentiment") == "negative"]
            if neg_articles:
                news_section += "\n**Source Articles:**\n"
                for m in neg_articles[:5]:
                    news_section += (
                        f"- **{m.get('source', '')}**: {m.get('headline', '')}  \n"
                        f"  _{m.get('snippet', '')[:200]}_  \n"
                        f"  {m.get('url', '')}\n"
                    )

        return REPORT_TEMPLATE.format(
            entity_id=entity_id,
            entity_type=entity_type,
            timestamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"),
            investigation_id=str(uuid.uuid4())[:8].upper(),
            risk_score=risk_score,
            risk_level=f"{'🔴' if risk_level == 'CRITICAL' else '🟠' if risk_level == 'HIGH' else '🟡' if risk_level == 'MEDIUM' else '🟢'} {risk_level}",
            indicator_count=len(fraud_indicators),
            checks_completed="Web Scraping, SQL Analysis, Knowledge Graph",
            fraud_summary_section=fraud_summary_section,
            fraud_indicators_section=render_indicators(fraud_indicators),
            web_section=web_section,
            news_section=news_section,
            sql_section=sql_section,
            graph_section=graph_section,
            recommendations_section=bullet_list(recommendations),
            recommended_action=self._score_to_action(risk_score, risk_level)
        )

    async def run(
        self,
        entity_id: str,
        entity_type: str,
        web_intelligence: Dict,
        sql_findings: Dict,
        graph_insights: Dict,
        customer_info: Dict = None,  # ← NEW: passed from orchestrator
    ) -> Dict[str, Any]:

        logger.info(f"RiskSynthesizerAgent running for {entity_type}:{entity_id}")

        web_intelligence = _safe_dict(web_intelligence, "web_intelligence")
        sql_findings     = _safe_dict(sql_findings,     "sql_findings")
        graph_insights   = _safe_dict(graph_insights,   "graph_insights")
        customer_info    = customer_info or {}

        # Compute composite risk score — customer_info passed directly
        risk_score = self._compute_risk_score(
            web_intelligence, sql_findings, graph_insights, customer_info
        )
        risk_level = self._score_to_level(risk_score)

        fraud_indicators = self._collect_fraud_indicators(web_intelligence, sql_findings, graph_insights)

        fraud_summary = ""
        if fraud_indicators:
            indicator_text = "\n".join(
                f"- [{ind['source']}] {ind['flag']}: {ind['description']}"
                for ind in fraud_indicators
            )
            summary_prompt = (
                f"Entity: {entity_id} ({entity_type})\n"
                f"Risk Score: {risk_score:.2f} → {risk_level}\n\n"
                f"Fraud Indicators Found:\n{indicator_text}\n\n"
                f"News/Web Intelligence: {web_intelligence.get('news_narrative', 'N/A')}\n\n"
                f"Write a concise but detailed fraud summary paragraph (5-8 sentences) for a compliance officer. "
                f"Cover: what type of fraud is suspected, key evidence, financial exposure, "
                f"and urgency of action required. Be specific — use actual figures and details from the indicators above. "
                f"Do NOT use bullet points — write flowing prose."
            )
            try:
                summary_resp = await self.llm.ainvoke([
                    SystemMessage(content=self.SYSTEM_PROMPT),
                    HumanMessage(content=summary_prompt)
                ])
                if isinstance(summary_resp, list):
                    raw = next(
                        (m.content for m in reversed(summary_resp) if hasattr(m, "content")),
                        ""
                    )
                elif isinstance(summary_resp, str):
                    raw = summary_resp
                else:
                    raw = getattr(summary_resp, "content", "") or ""
                fraud_summary = raw.strip() if isinstance(raw, str) else ""
                logger.info(f"[RiskSynthesizer] LLM fraud summary generated ({len(fraud_summary)} chars)")
            except Exception as e:
                logger.warning(f"[RiskSynthesizer] LLM fraud summary failed: {e}")
                fraud_summary = ""

        synthesis_prompt = f"""
Entity: {entity_id} ({entity_type})
Composite Risk Score: {risk_score} → {risk_level}
Fraud Indicators:
{chr(10).join('- [' + i.get('source','') + '] ' + i.get('flag','') + ': ' + i.get('description','') for i in fraud_indicators) if fraud_indicators else 'None'}

Web Risk Score: {web_intelligence.get('web_risk_score', 0)}
SQL Risk Score: {sql_findings.get('sql_risk_score', 0)}
Graph Risk Score: {graph_insights.get('graph_risk_score', 0)}

Provide:
1. A list of 3-5 specific, actionable recommendations
2. Whether a SAR (Suspicious Activity Report) should be filed (true/false)
3. Recommended monitoring period in days

Return as JSON: {{recommendations: [...], file_sar: bool, monitoring_days: int}}
"""
        risk_output: Optional[RiskSynthesisOutput] = None
        try:
            structured_llm = self.llm.with_structured_output(RiskSynthesisOutput)
            risk_output = await structured_llm.ainvoke([
                SystemMessage(content=self.SYSTEM_PROMPT),
                HumanMessage(content=synthesis_prompt)
            ])
        except Exception as e:
            logger.warning(f"[RiskSynthesizer] Structured LLM failed: {e}")
            risk_output = RiskSynthesisOutput(
                recommendations=[
                    "Conduct enhanced KYC verification",
                    "Review last 90 days of transaction history",
                    "Cross-reference counterparties against watchlists",
                    "Alert compliance team if risk is HIGH or above",
                    "Schedule callback verification with customer"
                ],
                file_sar=risk_score > 0.8,
                monitoring_days=90 if risk_level in ("HIGH", "CRITICAL") else 30,
                rationale=f"Fallback assessment: composite risk score {risk_score:.2f} → {risk_level}"
            )

        recommendations = risk_output.recommendations
        file_sar        = risk_output.file_sar
        monitoring_days = risk_output.monitoring_days

        report = self._build_report(
            entity_id, entity_type, risk_score, risk_level,
            fraud_indicators, fraud_summary, recommendations,
            web_intelligence, sql_findings, graph_insights
        )

        return {
            "entity_id":        entity_id,
            "risk_score":       risk_score,
            "risk_level":       risk_level,
            "fraud_indicators": fraud_indicators,
            "fraud_summary":    fraud_summary,
            "recommendations":  recommendations,
            "file_sar":         file_sar,
            "monitoring_days":  monitoring_days,
            "rationale":        risk_output.rationale,
            "report":           report,
            "timestamp":        datetime.utcnow().isoformat() + "Z"
        }